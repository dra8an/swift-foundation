#!/usr/bin/env python3
# Generates the C target _FoundationCollationData: the bundled collation data (ucadata.icu, nfd.bin and the
# tailorings) compiled into the library as byte arrays, as swift-foundation-icu ships ICU's data
# (icu_packaged_main_data.*.inc.h). A CMake build has no resource bundle; with this target, SwiftPM and CMake
# builds read the same bytes from memory, with no file lookup at run time.
#
# Usage (from the repo root): python3 Collation/Tools/gen_collation_data.py
#   Reads  Sources/FoundationInternationalization/Collation/Resources/{ucadata.icu, nfd.bin, tailorings/*.bin}
#   Writes Sources/_FoundationCollationData/{collation_data.c, data/*.inc, include/_FoundationCollationData.h}
# Run it again after any change to those files. (The ICU4X variant, ucadata-icu4x.icu, is test-only data in
# Tests/FoundationInternationalizationTests/Collation/TestData/ and is not compiled in.)
import os, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(REPO, 'Sources/FoundationInternationalization/Collation/Resources')
OUT = os.path.join(REPO, 'Sources/_FoundationCollationData')

HEADER = '''//===----------------------------------------------------------------------===//
//
// This source file is part of the Swift.org open source project
//
// Copyright (c) 2026 Apple Inc. and the Swift project authors
// Licensed under Apache License v2.0 with Runtime Library Exception
//
// See https://swift.org/LICENSE.txt for license information
// See https://swift.org/CONTRIBUTORS.txt for the list of Swift project authors
//
//===----------------------------------------------------------------------===//
'''

def resources():
    items = [('ucadata', os.path.join(RES, 'ucadata.icu')), ('nfd', os.path.join(RES, 'nfd.bin'))]
    tdir = os.path.join(RES, 'tailorings')
    for f in sorted(os.listdir(tdir)):
        if f.endswith('.bin'):
            items.append(('tailorings/' + f[:-4], os.path.join(tdir, f)))
    return sorted(items)  # sorted by name: the lookup is a binary search

def c_name(name):
    return '_collation_data_' + ''.join(ch if ch.isalnum() else '_' for ch in name)

def main():
    items = resources()
    os.makedirs(os.path.join(OUT, 'data'), exist_ok=True)
    os.makedirs(os.path.join(OUT, 'include'), exist_ok=True)
    for old in os.listdir(os.path.join(OUT, 'data')):
        if old.endswith('.inc'):
            os.remove(os.path.join(OUT, 'data', old))
    total = 0
    for name, path in items:
        data = open(path, 'rb').read()
        total += len(data)
        lines = [','.join('0x%02x' % b for b in data[i:i + 24]) for i in range(0, len(data), 24)]
        with open(os.path.join(OUT, 'data', c_name(name)[len('_collation_data_'):] + '.inc'), 'w') as f:
            f.write('// Generated by Collation/Tools/gen_collation_data.py from %s (%d bytes). Do not edit.\n'
                    % (os.path.relpath(path, REPO), len(data)))
            f.write(',\n'.join(lines) + '\n')
    with open(os.path.join(OUT, 'include', '_FoundationCollationData.h'), 'w') as f:
        f.write(HEADER + '''
#ifndef _FOUNDATION_COLLATION_DATA_H
#define _FOUNDATION_COLLATION_DATA_H

#include <stddef.h>

/// The bytes of a bundled collation resource — "ucadata" (the root data), "nfd" (the normalization data) or
/// "tailorings/<name>" (a compiled tailoring) — and their count in `length`; NULL (and length 0) for an unknown name.
/// The memory is static and immutable.
const unsigned char * _Nullable _foundation_collation_resource(const char * _Nonnull name, size_t * _Nonnull length);

#endif
''')
    with open(os.path.join(OUT, 'collation_data.c'), 'w') as f:
        f.write(HEADER + '''
// Generated by Collation/Tools/gen_collation_data.py. Do not edit.

#include "_FoundationCollationData.h"
#include <string.h>

''')
        for name, path in items:
            f.write('static const unsigned char %s[] = {\n#include "data/%s.inc"\n};\n'
                    % (c_name(name), c_name(name)[len('_collation_data_'):]))
        f.write('''
struct _collation_resource { const char *name; const unsigned char *bytes; size_t length; };

/// Sorted by name.
static const struct _collation_resource _collation_resources[] = {
''')
        for name, path in items:
            f.write('    { "%s", %s, sizeof(%s) },\n' % (name, c_name(name), c_name(name)))
        f.write('''};

const unsigned char *_foundation_collation_resource(const char *name, size_t *length) {
    size_t lo = 0, hi = sizeof(_collation_resources) / sizeof(_collation_resources[0]);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        int order = strcmp(name, _collation_resources[mid].name);
        if (order == 0) {
            *length = _collation_resources[mid].length;
            return _collation_resources[mid].bytes;
        }
        if (order < 0) { hi = mid; } else { lo = mid + 1; }
    }
    *length = 0;
    return NULL;
}
''')
    print('%d resources, %d bytes, written to %s' % (len(items), total, os.path.relpath(OUT, REPO)))

if __name__ == '__main__':
    main()
