private enum VarE {   // derived starts, prefix walk, ~425 B, O(n)
    static func year(_ i: Int) -> (ny: Int, bits: UInt16, count: Int, leap: Int) {
        var s = anchorRD
        for j in 0..<i { s += Var16.length(j) }
        let d = Var16.decode(i)
        return (s, d.bits, d.count, d.leap)
    }
}

@Suite("Chinese Packing Experiment")
private struct ChinesePackingExperiment {
    @Test func packingCorrectnessAndBench() {
        // Correctness: every variant decodes identically to the baseline for all 200 years.
        for i in 0..<200 {
            let a = VarA.year(i)
            for (name, y) in [("B", VarB.year(i)), ("C", VarC.year(i)), ("D", VarD.year(i)), ("E", VarE.year(i))] {
                #expect(y == a, "variant \(name) year \(i)")
            }
        }
        print("PACK correctness: B/C/D/E all identical to baseline for 200 years")

        // Microbench: hot pattern = year lookup + month walk, cycling the table.
        func bench(_ name: String, _ f: (Int) -> (ny: Int, bits: UInt16, count: Int, leap: Int)) {
            var checksum = 0
            for i in 0..<200 { let y = f(i); checksum &+= y.ny &+ Int(y.bits) }   // warm-up
            let n = 200_000
            let t0 = ProcessInfo.processInfo.systemUptime
            for k in 0..<n {
                let y = f(k % 200)
                var start = y.ny
                for o in 1...y.count { start += (y.bits >> (o - 1) & 1 == 1) ? 30 : 29 }
                checksum &+= start
            }
            let el = ProcessInfo.processInfo.systemUptime - t0
            print("PACK bench \(name): \(Int(el * 1e9 / Double(n))) ns/op")
            #expect(checksum != 0)
        }
        bench("A-UInt32-800B", VarA.year)
        bench("B-3byte-600B", VarB.year)
        bench("C-16bit+off-575B", VarC.year)
        bench("D-16bit-cache-425B+heap", VarD.year)
        bench("E-16bit-walk-425B", VarE.year)
    }
}
